-- VocabBank: Supabase becomes the primary database.
-- Run this whole file in Supabase SQL Editor once.
-- RLS ensures every signed-in user can only access their own rows.

create table if not exists public.vocab_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  id text not null,
  data jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, id)
);

create table if not exists public.grammar_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  id text not null,
  data jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, id)
);

create table if not exists public.user_settings (
  user_id uuid not null references auth.users(id) on delete cascade,
  key text not null,
  data jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, key)
);

create table if not exists public.review_logs (
  user_id uuid not null references auth.users(id) on delete cascade,
  id text not null,
  ts timestamptz not null,
  data jsonb not null,
  seq bigint generated by default as identity,
  primary key (user_id, id),
  unique (user_id, seq)
);

create index if not exists vocab_items_user_updated_idx
  on public.vocab_items(user_id, updated_at desc);
create index if not exists grammar_items_user_updated_idx
  on public.grammar_items(user_id, updated_at desc);
create index if not exists user_settings_user_updated_idx
  on public.user_settings(user_id, updated_at desc);
create index if not exists review_logs_user_seq_idx
  on public.review_logs(user_id, seq);
create index if not exists review_logs_user_ts_idx
  on public.review_logs(user_id, ts);

create or replace function public.set_vocabbank_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists vocab_items_set_updated_at on public.vocab_items;
create trigger vocab_items_set_updated_at
before insert or update on public.vocab_items
for each row execute function public.set_vocabbank_updated_at();

drop trigger if exists grammar_items_set_updated_at on public.grammar_items;
create trigger grammar_items_set_updated_at
before insert or update on public.grammar_items
for each row execute function public.set_vocabbank_updated_at();

drop trigger if exists user_settings_set_updated_at on public.user_settings;
create trigger user_settings_set_updated_at
before insert or update on public.user_settings
for each row execute function public.set_vocabbank_updated_at();

